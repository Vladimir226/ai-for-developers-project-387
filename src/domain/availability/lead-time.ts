// Минимальный запас до звонка (спецификация #22, тикет #23): единая точка
// правила «слишком рано». Владелец получает минимум 30 минут на подготовку
// к звонку: слот и выдаётся, и бронируется, только если его старт не раньше
// now + MIN_LEAD_TIME_MS — старт ровно на границе допустим. Правило живёт
// на сервере (ADR-004), величина — константа домена без настроек и секретов;
// сравнение мгновений в UTC (ADR-009). Уже начавшиеся старты тоже «слишком
// рано», но бронирование отвечает за них кодом SLOT_IN_PAST — прошлое
// проверяется раньше (приоритет ошибок createBooking).

/** Минимальный запас от момента брони до начала звонка: 30 минут (#22). */
export const MIN_LEAD_TIME_MS = 30 * 60 * 1000;

/** Начинается ли слот раньше границы минимального запаса (включая прошлое). */
export function isSlotTooSoon(startsAt: Date, now: Date): boolean {
  return startsAt.getTime() < now.getTime() + MIN_LEAD_TIME_MS;
}
