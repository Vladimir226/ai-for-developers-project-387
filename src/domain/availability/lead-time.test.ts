import { describe, expect, it } from 'vitest';
import { isSlotTooSoon } from './lead-time';

// Граница правила минимального запаса до звонка (#22/#23): слот бронируется
// и выдаётся, только если начинается не раньше чем через 30 минут после
// текущего момента; старт ровно на границе допустим. Порог зашит в литералы
// таймстампов (12:29:59 / 12:30:00), а не взят из константы домена — смена
// величины запаса обязана ронять эти тесты (шов 3, независимо от формулы).

const NOW = new Date('2026-11-07T12:00:00Z');

describe('isSlotTooSoon — граница минимального запаса', () => {
  it('старт через 29 минут 59 секунд — слишком рано', () => {
    expect(isSlotTooSoon(new Date('2026-11-07T12:29:59Z'), NOW)).toBe(true);
  });

  it('старт ровно через 30 минут — допустим (граница включена)', () => {
    expect(isSlotTooSoon(new Date('2026-11-07T12:30:00Z'), NOW)).toBe(false);
  });

  it('старт через 30 минут 1 секунду — допустим', () => {
    expect(isSlotTooSoon(new Date('2026-11-07T12:30:01Z'), NOW)).toBe(false);
  });

  it('близкое будущее и уже начавшийся старт — слишком рано', () => {
    expect(isSlotTooSoon(new Date('2026-11-07T12:10:00Z'), NOW)).toBe(true);
    expect(isSlotTooSoon(new Date('2026-11-07T11:59:59Z'), NOW)).toBe(true);
  });
});
